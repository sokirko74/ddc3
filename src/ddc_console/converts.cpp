char wtk(char c)
{
        
    c&= 0377;
    if(c & 0200)
        c       = wk[c & 0177];
    return c;
}
char ktw(char c)
{
    c&= 0377;
    if(c & 0200)
        c       = kw[c & 0177];
    return c;
}


void WinToKOI8 (string& s)
{
    int count = s.length();
    for (int i=0; i< count; i++)
        s[i] = wtk(s[i]);
};

void KOI8ToWin (string& s)
{
    int count = s.length();
    for (int i=0; i< count; i++)
        s[i] = ktw(s[i]);
};

